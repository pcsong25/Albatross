"""The writer: an exposition of the development, on request.

This is the one role whose output is not checked for mathematical content, because
it is not supposed to have any of its own. It reorganises: hypothesis lists become
sentences, routine lemmas move inside the proofs that use them, machine identifiers
become "the energy estimate of Lemma 3", and the dependency order becomes the order
a paper is read in. Everything it says is meant to already be in the development.

That is also why it cannot be trusted, and why the shape here is the same as
everywhere else in this system:

*Code enumerates; the model judges.* The outline assigns every active node to a
section and :func:`bp.paper.check_outline` refuses one that drops a node or places
it twice. Each section declares which of its nodes it stated — with a checkable
``\\label`` — and which it merged, and :func:`bp.paper.check_section` refuses a
section that is silent about one of them. Neither check can tell whether the prose
is *faithful*; both guarantee that nothing was quietly left out, which is the
failure that would otherwise be invisible.

*Nothing here writes to the graph.* Not a note, not a status, not a hash. The role
produces a build artifact under ``.bp/paper/`` and touches nothing else, so a paper
that came out badly costs a rebuild and nothing more.

*The apparatus is not the model's to write.* The provenance note and the appendix
mapping every node to its section are generated by :mod:`bp.paper` from the graph.
An exposition that has lost something is then recoverable, which is the only honest
answer to "translating this may lose accuracy".
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from .. import ops, paper as paper_mod, render
from ..agents.base import AgentError, BudgetExceeded, CallMeta
