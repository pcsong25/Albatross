#: The role name. Configured in ``bp.yaml`` like every other; it inherits from the
#: decomposer when it is not configured, because writing mathematical prose from a
#: development is the job most like the decomposer's.
ROLE = "writer"

#: How much of each proof the *outline* call sees. The outline only has to decide
#: where a node belongs, and sending every proof in full made the one call that
#: reads the whole development the most expensive call in the system on a large
#: project. The section writer gets the full text of the proofs it is responsible
#: for, which is where the text is actually needed.
OUTLINE_PROOF_CHARS = 700

#: Rough token counts for the previewable bill. Same convention as
#: :mod:`bp.recompile`: the input side is measured, the output side is a constant
#: because it cannot be known before the call.
CHARS_PER_TOKEN = 4
OUTLINE_OUTPUT_TOKENS = 1500
SECTION_OUTPUT_TOKENS = 3000
#: What a project's section count is guessed at, for the estimate only, when no
#: outline exists yet. The real number is the outline's judgement.
SECTIONS_PER_NODE = 0.4
MIN_SECTIONS = 3
MAX_SECTIONS = 12


# --- what the model returns ---------------------------------------------------


class SectionPlan(BaseModel):
    model_config = ConfigDict(extra="forbid")

    heading: str = Field(description="the section heading, as it will be printed")
    purpose: str = Field(default="", description="one line: what this section is for")
    nodes: list[str] = Field(
        default_factory=list,
        description="ids of the development nodes whose content this section carries",
    )


class Outline(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: str = Field(description="the paper's title, in LaTeX")
    abstract: str = Field(default="", description="the abstract, as LaTeX prose")
    sections: list[SectionPlan] = Field(default_factory=list, max_length=20)
    notes: str = Field(
        default="",
        description="reservations about the plan, and anything the development's "
        "gaps stop the paper being able to claim",
    )


class MergedNode(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(description="the node id you folded into the prose")
    where: str = Field(
        default="", description="what it became: 'Step 2 of the proof of Lemma~\\ref{…}'"
    )


class SectionDraft(BaseModel):
    model_config = ConfigDict(extra="forbid")

    tex: str = Field(
        description="the body of the section, in LaTeX. No \\section heading, no "
        "preamble, no \\begin{document}"
    )
    stated: list[str] = Field(
        default_factory=list,
        description="node ids you gave their own labelled statement, each carrying "
        "\\label{paper:<id>} in the text",
    )
    merged: list[MergedNode] = Field(
        default_factory=list, description="node ids folded into prose instead"
    )
    departures: list[str] = Field(
        default_factory=list,
        description="where this exposition differs from the development in a way a "
        "careful reader should know",
    )
    lost: list[str] = Field(
        default_factory=list,
        description="anything in the source you could not carry over faithfully",
    )


# --- the report ---------------------------------------------------------------


@dataclass
class PaperReport:
    draft: paper_mod.Draft | None = None
    diagnostics: list[Diagnostic] = field(default_factory=list)
    calls: list[CallMeta] = field(default_factory=list)
    path: Path | None = None
    #: Set when the call cap or the dollar cap stopped the run. The sections that
    #: were never written are in the draft, marked as not written — a paper missing
    #: three sections must say so rather than look like a shorter paper.
    stopped: str = ""
    #: Sections whose call failed outright, by heading.
    failed: list[str] = field(default_factory=list)

    @property
    def clean(self) -> bool:
        return not any(d.severity == "error" for d in self.diagnostics)


@dataclass
class Estimate:
    """The previewable bill for a paper, before any call is made."""

    nodes: int = 0
    sections: int = 0
    calls: int = 0
    estimated_usd: float | None = None
    unpriced_calls: int = 0

    def describe(self) -> str:
        lines = [
            f"{self.nodes} node(s) to cover; the outline decides how many sections, "
            f"so this assumes about {self.sections}",
            f"{self.calls} model call(s): 1 for the outline, then one per section "
            "(one more for any section that has to be rewritten)",
        ]
        if self.estimated_usd:
            lines.append(f"estimated cost: ${self.estimated_usd:.2f}")
        if self.unpriced_calls:
            lines.append(
                f"{self.unpriced_calls} call(s) on a subscription backend, which "
                "reports no price — the call cap is what limits those"
            )
        lines.append(
            "this is a floor: a section rejected by the completeness check costs one "
            "more call"
        )
        return "\n".join(lines)


# --- context ------------------------------------------------------------------


def reading_order(graph: Graph) -> list[str]:
    """The order the development is presented to the writer in.

    The renderer's own order — dependencies first, target last, then whatever the
    target does not reach — so the writer sees the development in exactly the order
    the document it is replacing uses, and its decision to reorder is a decision
    rather than an accident.
    """
    main, rest = render.order_entries(graph)
    return [*main, *rest]


def _status_line(node: Node) -> str:
    bits = [f"status: {node.global_status or '?'} (local: {node.local_status})"]
    if node.status_reason:
        bits.append(f"reason: {node.status_reason}")
    if not node.proof_section.strip():
        bits.append("NO PROOF IS WRITTEN FOR THIS NODE")
    if node.local_status in {"admitted", "assumption"}:
        bits.append(
            "this is NOT proved in the development — it may only be presented as an "
            "assumption"
        )
    return ". ".join(bits) + "."


def _node_material(node: Node, graph: Graph, *, proof_chars: int | None) -> str:
    proof = node.proof_section.strip() or "(none written)"
    if proof_chars is not None and len(proof) > proof_chars:
        proof = proof[:proof_chars].rstrip() + f"\n\n[…{len(proof) - proof_chars} more characters]"
    parts = [
        f"### `{node.id}`",
        "",
        f"Role: {node.role}. Difficulty: {node.difficulty}. "
        + ("This is the target. " if node.target else "")
        + _status_line(node),
        "",
        f"Label to use if you state it: `{paper_mod.label_for(node.id)}`",
        "",
        "Hypotheses:",
        "",
        "\n".join(f"- {h.id}: {h.tex}" for h in node.hypotheses) or "(none)",
        "",
        "Statement:",
        "",
        node.statement_section.strip() or "(not written)",
        "",
        "Proof:",
        "",
        proof,
    ]
    if node.children:
        parts += ["", "Lemmas it cites: " + ", ".join(f"`{c}`" for c in node.children)]
    uses = context.uses_block(node)
    if uses:
        parts += ["", uses]
    return "\n".join(parts)


def development_block(
    graph: Graph, order: list[str], *, proof_chars: int | None = None
) -> str:
    lines = [
        "## The development",
        "",
        "In dependency order: every node appears before the argument that uses it. "
        "That is the order it must be *proved* in, not the order it should be read "
        "in.",
        "",
    ]
    for node_id in order:
        node = graph.get(node_id)
        if node is not None:
            lines.append(_node_material(node, graph, proof_chars=proof_chars))
            lines.append("")
    return "\n".join(lines).strip()


def _catalogue(graph: Graph, order: list[str]) -> str:
    """Every node with a one-line summary — what the outline is choosing among."""
    lines = ["## Every node, in one line each", ""]
    for node_id in order:
        node = graph.get(node_id)
        if node is None:
            continue
        head = " ".join(node.statement_section.split())[:180]
        lines.append(
            f"- `{node.id}` ({node.role}, {node.difficulty}, "
            f"{node.global_status or '?'}"
            + (", TARGET" if node.target else "")
            + f"): {head}"
        )
    return "\n".join(lines)


def outline_prompt(project: Project, graph: Graph, order: list[str], guidance: str) -> str:
    return context.join(
        context.preamble_block(project),
        _catalogue(graph, order),
        development_block(graph, order, proof_chars=OUTLINE_PROOF_CHARS),
        "## What to plan"
        "\n\nAssign every one of the "
        f"{len(order)} nodes above to exactly one section. The ids are listed in the "
        "catalogue; use them verbatim.",
        (
            "## The user's guidance\n\nThis is from the mathematician whose paper this "
            f"is. It outranks your own instinct about the shape.\n\n{guidance.strip()}"
            if guidance
            else ""
        ),
    )


def _outline_summary(outline: Outline, index: int) -> str:
    lines = ["## The paper you are writing one section of", "", f"Title: {outline.title}", ""]
    if outline.abstract.strip():
        lines += ["Abstract:", "", outline.abstract.strip(), ""]
    lines.append("Sections, in order:")
    lines.append("")
    for i, section in enumerate(outline.sections):
        mark = "  <-- YOURS" if i == index else ""
        lines.append(f"{i + 1}. **{section.heading}** — {section.purpose}{mark}")
        if section.nodes:
            lines.append(f"    covers: {', '.join('`' + n + '`' for n in section.nodes)}")
    return "\n".join(lines)


def _label_map(outline: Outline, graph: Graph) -> str:
    """Every label the paper will contain, and which section owns it.

    Without this a section could only reference results it stated itself, and the
    prose would fall back to naming node ids — the thing this whole role exists to
    stop.
    """
    lines = [
        "## Labels you may reference",
        "",
        "Each node of the development has one label. If another section states the "
        "node, `\\ref` resolves to its number there; reference nothing else.",
        "",
    ]
    for i, section in enumerate(outline.sections):
        for node_id in section.nodes:
            node = graph.get(node_id)
            if node is None:
                continue
            head = " ".join(node.statement_section.split())[:110]
            lines.append(
                f"- `{paper_mod.label_for(node_id)}` (section {i + 1}, "
                f"{node.role}): {head}"
            )
    return "\n".join(lines)


def section_prompt(
    project: Project,
    graph: Graph,
    outline: Outline,
    index: int,
    guidance: str,
) -> str:
    plan = outline.sections[index]
    assigned = [n for n in plan.nodes if n in graph.active]
    material = "\n\n".join(
        _node_material(graph[n], graph, proof_chars=None) for n in assigned
    )
    return context.join(
        context.preamble_block(project),
        _outline_summary(outline, index),
        _label_map(outline, graph),
        f"## Your section: {plan.heading}\n\n{plan.purpose}",
        (
            "## The material for your section\n\n"
            "These are the nodes assigned to you. Every one of them must end up in "
            "`stated` or in `merged`.\n\n" + material
        )
        if assigned
        else (
            "## Your section carries no nodes\n\nIt is introduction, motivation or "
            "connective prose. Write it from the outline and the other sections' "
            "material; state no new mathematics, and return empty `stated` and "
            "`merged` lists."
        ),
        (
            f"## The user's guidance\n\n{guidance.strip()}"
            if guidance
            else ""
        ),
    )


# --- the estimate -------------------------------------------------------------


def estimate(project: Project, *, registry: Registry | None = None) -> Estimate:
    """What building the paper would cost. Deterministic, and makes no call."""
    registry = registry or Registry(project)
    graph, _, swept = load_graph(project)
    order = reading_order(graph) if swept else sorted(graph.active)
    sections = max(MIN_SECTIONS, min(MAX_SECTIONS, round(len(order) * SECTIONS_PER_NODE)))
    result = Estimate(nodes=len(order), sections=sections, calls=1 + sections)
    if not swept:
        return result

    agent = registry.agent(ROLE)
    outline_in = len(outline_prompt(project, graph, order, "")) // CHARS_PER_TOKEN
    # One section's prompt is the outline summary plus its share of the material.
    body = len(development_block(graph, order)) // CHARS_PER_TOKEN
    section_in = outline_in // 3 + (body // max(1, sections))

    total = 0.0
    for in_tokens, out_tokens, n in (
        (outline_in, OUTLINE_OUTPUT_TOKENS, 1),
        (section_in, SECTION_OUTPUT_TOKENS, sections),
    ):
        price = agent.estimate_usd(in_tokens, out_tokens)
        if price is None:
            result.unpriced_calls += n
        else:
            total += price * n
    result.estimated_usd = total if total else None
    return result


# --- the role -----------------------------------------------------------------


def write(
    project: Project,
    *,
    registry: Registry | None = None,
    title: str | None = None,
    guidance: str = "",
    repair_rounds: int = 1,
    observer=None,
) -> PaperReport:
    """Write the paper. One outline call, then one call per section.

    Writes ``.bp/paper/paper.json`` and nothing else — no node file, no event, no
    status. The LaTeX is rendered from the draft afterwards by
    :func:`bp.paper.document`, as often as wanted, for free.
    """
    registry = registry or Registry(project)
    agent = registry.agent(ROLE)
    timeout = registry.config.role(ROLE).timeout

    graph, load_diagnostics, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` before writing a paper")
    if any(d.severity == "error" for d in load_diagnostics):
        # Same refusal as `cli._graph`: a paper written from a graph that only
        # partly loaded is a paper about a project the user does not have.
        raise ops.OpError(
            "some node files could not be loaded, so the development is incomplete; "
            "run `bp check` and fix those first — a paper written from part of a graph "
            "would read as a complete argument"
        )
    if not graph.active:
        raise ops.OpError("there are no active nodes to write about")

    order = reading_order(graph)
    report = PaperReport()

    # --- the outline ---------------------------------------------------------
    user = outline_prompt(project, graph, order, guidance)
    outline: Outline | None = None
    outline_diagnostics: list[Diagnostic] = []
    for attempt in range(repair_rounds + 1):
        outline, meta = agent.complete(
            context.load_prompt("paper_outline"), user, Outline, timeout
        )
        report.calls.append(meta)
        outline_diagnostics = paper_mod.check_outline(
            {s.heading: list(s.nodes) for s in outline.sections}, graph
        )
        if not any(d.severity == "error" for d in outline_diagnostics):
            break
        if attempt == repair_rounds:
            break
        user = context.join(
            outline_prompt(project, graph, order, guidance),
            context.diagnostics_block(
                outline_diagnostics, "Your previous outline was rejected"
            ),
            "Return a corrected outline. Every node id in the catalogue must appear in "
            "exactly one section's `nodes`. If a node does not deserve a statement of "
            "its own, still assign it — the section that will absorb it into a proof is "
            "its home.",
        )
    assert outline is not None
    report.diagnostics.extend(outline_diagnostics)

    # Deduplicate deterministically: the first section to claim a node keeps it,
    # which is what `check_outline` reported.
    claimed: set[str] = set()
    plan: list[tuple[SectionPlan, list[str]]] = []
    for section in outline.sections:
        mine = [n for n in section.nodes if n in graph.active and n not in claimed]
        claimed.update(mine)
        plan.append((section, mine))
    unplaced = sorted(set(graph.active) - claimed)

    # --- one call per section ------------------------------------------------
    records: list[paper_mod.Section] = []
    stopped = ""
    outline_for_prompt = Outline(
        title=outline.title,
        abstract=outline.abstract,
        sections=[
            SectionPlan(heading=s.heading, purpose=s.purpose, nodes=mine)
            for s, mine in plan
        ],
        notes=outline.notes,
    )
    for index, (section, mine) in enumerate(plan):
        record = paper_mod.Section(
            heading=section.heading, purpose=section.purpose, nodes=list(mine)
        )
        if stopped:
            record.failed = stopped
            records.append(record)
            continue
        if observer is not None:
            observer(index, len(plan), section.heading)
        try:
            draft, diagnostics = _write_section(
                project, graph, outline_for_prompt, index, mine, guidance,
                agent=agent, timeout=timeout, repair_rounds=repair_rounds,
                calls=report.calls,
            )
        except BudgetExceeded as exc:
            # Never swallowed: the cap is the thing standing between a paper and an
            # unattended afternoon. Every remaining section is recorded as not
            # written, so the document says what happened instead of looking short.
            stopped = f"the run's cap stopped the paper here — {exc}"
            record.failed = stopped
            records.append(record)
            continue
        except AgentError as exc:
            record.failed = f"the writer could not produce this section: {exc}"
            report.failed.append(section.heading)
            records.append(record)
            continue
        record.tex = draft.tex
        record.stated = [n for n in draft.stated]
        record.merged = [paper_mod.Merge(id=m.id, where=m.where) for m in draft.merged]
        record.departures = list(draft.departures)
        record.lost = list(draft.lost)
        records.append(record)
        report.diagnostics.extend(diagnostics)
    report.stopped = stopped

    # A section with no text is `PAP006` however it got that way — a failed call or a
    # cap that fired. Reported here rather than in the two `except` branches so that
    # "the budget stopped us" cannot be the one path that reports a clean paper.
    for record in records:
        if record.failed:
            report.diagnostics.extend(paper_mod.check_section(record, graph))

    target = graph.target
    known = [m.cost_usd for m in report.calls if m.cost_usd is not None]
    result = paper_mod.Draft(
        title=(title or outline.title).strip() or "Proof development",
        abstract=outline.abstract,
        built_at=paper_mod.now(),
        target=target.id if target is not None else None,
        fingerprint=paper_mod.fingerprint(graph),
        sections=records,
        unplaced=unplaced,
        notes=outline.notes,
        calls=len(report.calls),
        cost_usd=sum(known) if known else None,
        diagnostics=list(report.diagnostics),
    )
    report.draft = result
    report.path = paper_mod.save(project, result)
    return report


def _write_section(
    project: Project,
    graph: Graph,
    outline: Outline,
    index: int,
    assigned: list[str],
    guidance: str,
    *,
    agent,
    timeout: float,
    repair_rounds: int,
    calls: list[CallMeta],
) -> tuple[SectionDraft, list[Diagnostic]]:
    """One section, repaired once against the completeness check."""
    system = context.load_prompt("paper_section")
    user = section_prompt(project, graph, outline, index, guidance)
    draft: SectionDraft | None = None
    diagnostics: list[Diagnostic] = []
    for attempt in range(repair_rounds + 1):
        draft, meta = agent.complete(system, user, SectionDraft, timeout)
        calls.append(meta)
        probe = paper_mod.Section(
            heading=outline.sections[index].heading,
            nodes=list(assigned),
            tex=draft.tex,
            stated=list(draft.stated),
            merged=[paper_mod.Merge(id=m.id, where=m.where) for m in draft.merged],
        )
        diagnostics = paper_mod.check_section(probe, graph)
        if not any(d.severity == "error" for d in diagnostics):
            break
        if attempt == repair_rounds:
            break
        user = context.join(
            section_prompt(project, graph, outline, index, guidance),
            context.diagnostics_block(diagnostics, "Your previous section was rejected"),
            "Return the corrected section. Keep the prose you had; the usual fix is a "
            "missing `\\label{paper:<id>}`, or a node you dealt with but did not list "
            "in `stated` or `merged`.",
        )
    assert draft is not None
    return draft, diagnostics


def summarise(report: PaperReport) -> str:
    if report.draft is None:
        return "no paper was written"
    lines = [
        f"{len(report.draft.sections)} section(s), {len(report.calls)} call(s)",
    ]
    for section in report.draft.sections:
        if section.failed:
            lines.append(f"  {section.heading}: NOT WRITTEN — {section.failed}")
            continue
        lines.append(
            f"  {section.heading}: {len(section.stated)} stated, "
            f"{len(section.merged)} merged"
        )
        for text in section.lost:
            lines.append(f"    not carried over: {text}")
    errors = [d for d in report.diagnostics if d.severity == "error"]
    if errors:
        lines.append(f"  {len(errors)} unresolved problem(s):")
        for d in errors:
            lines.append(f"    {d.code}: {d.message}")
    if report.stopped:
        lines.append(f"  stopped: {report.stopped}")
    return "\n".join(lines)


