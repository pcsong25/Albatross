"""The verifier: three jobs, kept apart and separately cached, then confirmation.

The three exist because they fail differently, and merging them to save calls
would give up the only thing that makes agent verification worth running.

**1. Obligation checks.** Consume ``bp obligations <node>`` one discharge record at
a time. Each is self-contained — does this source give this hypothesis, for this
object — with no proof search, no strategy and no whole-proof context. This is the
*misattribution* check: the answer to "the table says ``H2`` comes from ``H1``, but
does it?"

**2. Claim checks.** One record per ledger claim with a source, in the same narrow
shape: does the named source justify this claim, as applied here? This is where
premise smuggling dies — a claim the prose attributes to a lemma that does not give
it looks exactly like a claim the prose attributes to a lemma that does, until
somebody asks about that one claim on its own.

**3. Whole-proof pass.** The statement, the proof, and the children's statements
*as assumptions*. This catches what per-claim checking cannot: gaps *between*
individually correct claims, and whether the claims collectively reach the
conclusion. Two backends from different families, no shared context — two models
trained by the same lab miss the same things.

Both worklists are generated by code (:mod:`bp.discharge`, :mod:`bp.ledger`), which
is the whole point: "no objection" then means *all N enumerated checks passed*, not
*nothing caught my eye*. Results are cached on each record's content hash, so
editing one paragraph of a proof does not re-bill the rest.

**Confirmation.** Every objection from any of the three is re-presented with its
surrounding context and dropped if the flaw dissolves. This pass is not optional at
any level. Without it the output is mostly pedantry, the user stops reading it, and
the one real objection goes with the rest.

What this module never does is decide a status. It assembles a
:class:`bp.model.VerificationRecord`, and :mod:`bp.verification` derives
``local_status`` from that.
"""

