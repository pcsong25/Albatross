#: Which jobs each level runs. ``quick`` is for iterating; ``standard`` is routine
#: work; ``deep`` is what you run before trusting a subtree or writing it up.
#: Confirmation is in every level on purpose — see the module docstring.
LEVEL_JOBS: dict[str, frozenset[str]] = {
    verification.QUICK: frozenset({"whole_proof", "confirm"}),
    verification.STANDARD: frozenset(
        {"extract", "obligations", "references", "whole_proof", "confirm"}
    ),
    verification.DEEP: frozenset(
        {
            "extract",
            "obligations",
            "references",
            "claims",
            "audit",
            "whole_proof",
            "confirm",
        }
    ),
}

#: The default panel. Actual membership comes from `bp.yaml` (`agents.panel`) via
#: `Config.panel`, so a project can add a third reader or drop to one.
PANEL = ("verifier_a", "verifier_b")


def jobs_for(level: str) -> frozenset[str]:
    try:
        return LEVEL_JOBS[level]
    except KeyError:
        raise ops.OpError(
            f"unknown level {level!r}; the levels are "
            + ", ".join(verification.LEVELS)
        ) from None


class ObligationVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    entails: bool = Field(
        description="true only if the named source really gives the needed hypothesis "
        "for the stated object"
    )
    why: str = Field(description="one or two sentences")
    confidence: str = Field(default="medium", description="low | medium | high")


class BatchItem(ObligationVerdict):
    """One verdict inside a batched reply, tagged with the record it answers."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(description="the `id` of the record this verdict answers")


class BatchVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    verdicts: list[BatchItem] = Field(
        description="exactly one entry per record you were given, with its id"
    )


class CircularityVerdict(BaseModel):
    """Is a citation of an ancestor being *used* or merely *named*?

    Deliberately not phrased as ``entails``, which would read backwards: the healthy
    answer here is a **no**. Naming the object under discussion is fine; consuming
    what the ancestor asserts is a loop with no bottom.
    """

    model_config = ConfigDict(extra="forbid")

    used_as_fact: bool = Field(
        description="true if the citing passage consumes something the cited "
        "statement asserts — as a hypothesis, a step, a bound, or a conclusion. "
        "false if it only names the object, fixes notation, or orients the reader."
    )
    why: str = Field(description="one or two sentences, quoting what is taken if any")
    confidence: str = Field(default="medium", description="low | medium | high")


class Objection(BaseModel):
    model_config = ConfigDict(extra="forbid")

    section: str = Field(default="proof", description="statement | proof")
    quote: str = Field(description="the exact sentence or display this applies to")
    kind: str = Field(description="the class of error")
    why: str = Field(description="why it does not hold")
    confidence: str = Field(default="medium", description="low | medium | high")


class ProofVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    checked: list[str] = Field(
        description="what you went through, step by step. Required either way."
    )
    objections: list[Objection] = Field(default_factory=list)


class Confirmation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    upheld: bool
    why: str = Field(description="one sentence: the flaw, or what resolved it")


@dataclass
class Flag:
    """An objection that survived confirmation."""

    source: str
    section: str
    quote: str
    kind: str
    why: str
    raised_by: str
    #: A structural fact about the graph that the objection depends on — which node
    #: rests on which, for instance. Kept apart from ``why`` because confirmation
    #: rewrites ``why`` with its own sharper sentence, and for a circular citation the
    #: graph fact is the part the reader most needs and the part a model restating the
    #: objection is least likely to reproduce.
    context: str = ""

    def to_record(self) -> dict[str, Any]:
        record = {
            "kind": self.kind,
            "section": self.section,
            "quote": self.quote,
            "why": self.why,
            "raised_by": self.raised_by,
        }
        if self.context:
            record["context"] = self.context
        return record


@dataclass
class VerifyReport:
    node: str
    level: str = verification.STANDARD
    obligations_total: int = 0
    obligations_checked: int = 0
    obligations_cached: int = 0
    obligations_flagged: int = 0
    claims_total: int = 0
    claims_checked: int = 0
    claims_cached: int = 0
    claims_flagged: int = 0
    references_total: int = 0
    references_checked: int = 0
    references_cached: int = 0
    references_flagged: int = 0
    #: Citations of an ancestor that the verifier judged to be *used as facts*. A
    #: loop with no bottom, and counted separately because it is a different failure
    #: from a citation that merely does not support its use.
    circular_citations: int = 0
    ledger_claims: int = 0
    ledger_unsourced: int = 0
    ledger_ran: bool = False
    #: How many panel members actually answered. Zero means nothing verified this
    #: proof, which must never be recorded as ``verified``.
    panel_ran: int = 0
    panel: dict[str, str] = field(default_factory=dict)
    statement_audit: str = verification.NOT_RUN
    #: Set when the call cap stopped the confirmation pass. The verification is
    #: still recorded — see `confirm` — but its objections are not all confirmed.
    confirm_stopped: str = ""
    models: dict[str, str] = field(default_factory=dict)
    flags: list[Flag] = field(default_factory=list)
    withdrawn: list[tuple[Flag, str]] = field(default_factory=list)
    checked: list[str] = field(default_factory=list)
    calls: list[CallMeta] = field(default_factory=list)
    record: Any = None
    verdict: str = "verified"

    @property
    def reasons(self) -> list[str]:
        return verification.reasons(self.record) if self.record is not None else []


# --- the bill, before anything is spent ---------------------------------------
#
# Every worklist a verification consumes is computed by code from files on disk, so
# the number of calls is known *exactly* before the first one is made. Discovering
# it by spending the budget and failing was the original behaviour, and it cost a
# user forty calls — the whole cap — on a node whose `deep` level needed forty-one.
# Nothing was recorded, because a truncated worklist must never be recorded as a
# verification. Forty calls, no result, and no way to tell in advance.
#
# The only genuinely unpredictable term is confirmation: one call per objection, and
# how many objections there will be is the thing being asked. So the plan reports a
# floor and says so.


@dataclass
class VerifyPlan:
    """What a verification of one node will cost, per job, before it starts."""

    node: str
    level: str
    #: job -> (records, of those already cached, calls it will therefore make)
    jobs: dict[str, tuple[int, int, int]] = field(default_factory=dict)
    #: Calls the plan is certain about: everything except confirmation.
    calls: int = 0
    #: Cache hits, i.e. calls not being made because the answer is already bought.
    cached: int = 0

    @property
    def floor(self) -> int:
        """The smallest number of calls that can finish: ``calls`` plus nothing
        confirmed. One objection makes it one more."""
        return self.calls

    def lines(self) -> list[str]:
        out = []
        for job, (total, cached, calls) in self.jobs.items():
            note = f"   ({cached} of {total} already cached)" if cached else ""
            out.append(f"{job:<12} {calls:>3} call(s){note}")
        out.append(f"{'confirm':<12}   ? one per objection raised above")
        return out


def plan(
    project: Project,
    node_id: str,
    *,
    level: str = verification.STANDARD,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyPlan:
    """Count the calls a ``verify`` of this node at this level would make.

    Deterministic: reads the node files and the answer cache, makes no call, and
    needs no credentials. This is what ``--dry-run`` prints and what the browser
    shows before the button is live.
    """
    from ..ledger import claim_obligations_for, ledger_is_stale

    graph, _, _ = load_graph(project)
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")
    jobs = jobs_for(level)
    cache = load_cache(project) if use_cache else {}
    out = VerifyPlan(node=node_id, level=level)
    size = max(1, int(batch))

    def worklist(name: str, records: list[dict[str, Any]], batched: bool) -> None:
        total = len(records)
        cached = sum(1 for r in records if r["hash"] in cache) if use_cache else 0
        pending = total - cached
        # Batching only applies to the plain entailment shape; see `_answer_pending`.
        calls = -(-pending // size) if batched else pending
        out.jobs[name] = (total, cached, calls)
        out.calls += calls
        out.cached += cached

    if "extract" in jobs:
        needed = 1 if node.has_proof and (not node.claims or ledger_is_stale(node)) else 0
        out.jobs["extract"] = (needed, 0, needed)
        out.calls += needed
    if "obligations" in jobs:
        records = [r for r in obligations_for(node, graph) if r["kind"] != "admitted"]
        worklist("obligations", records, batched=True)
    if "references" in jobs:
        index = xref_mod.index_for(graph)
        worklist("references", xref_mod.reference_obligations_for(node, graph, index), False)
    if "claims" in jobs:
        worklist("claims", claim_obligations_for(node, graph), batched=False)
    if "whole_proof" in jobs:
        members = len(registry_panel(project))
        out.jobs["whole proof"] = (members, 0, members)
        out.calls += members
    if "audit" in jobs:
        out.jobs["audit"] = (1, 0, 1)
        out.calls += 1
    return out


def registry_panel(project: Project) -> list[str]:
    from ..agents.registry import load_config

    return list(load_config(project).panel)


def _preflight(
    project: Project,
    node_id: str,
    registry: Registry,
    *,
    level: str,
    batch: int,
) -> VerifyPlan:
    """Refuse a verification the budget cannot finish, *before* it costs anything.

    A cap that stops a run part-way through an enumerated worklist cannot be
    honoured by truncating it: "no objection in all 36 checks" and "no objection in
    the 30 checks we could afford" are different claims, and only the first is worth
    anything. So the run fails closed and records nothing — correct, and previously
    also the most expensive possible way to find out.

    The arithmetic is available for free. Doing it first turns forty wasted calls
    into an instant message with a number in it.
    """
    budget = registry.budget
    cap = budget.max_calls
    if cap is None:
        return plan(project, node_id, level=level, batch=batch)
    bill = plan(project, node_id, level=level, batch=batch)
    remaining = cap - budget.calls
    # No headroom is reserved for confirmation. It is the last step and it now
    # degrades rather than throwing (see `confirm`), so a run that fits everything
    # else is worth starting even if the objections go unconfirmed.
    if bill.floor <= remaining:
        return bill
    detail = "; ".join(
        f"{job} {calls}" for job, (_, _, calls) in bill.jobs.items() if calls
    )
    raise BudgetExceeded(
        # Opens with "call cap" so it reads as one of the budget family rather than
        # as a new class of failure: this is the same stop, moved earlier.
        f"call cap: a `{level}` verification of {node_id} needs at least "
        f"{bill.floor} calls "
        f"({detail}), plus one per objection raised — and the cap allows "
        f"{remaining} more. Refusing before spending anything, because a "
        f"verification that runs out part-way is not recorded and the calls are "
        f"wasted.\n"
        f"  * raise `budget.max_calls_per_run` in bp.yaml (currently {cap})\n"
        f"  * or use a cheaper level: `--level standard` drops the claim checks "
        f"and the statement audit\n"
        f"  * or `--batch 5` to ask the narrow checks five per call\n"
        f"Run `bp verify {node_id} --level {level} --dry-run` for the full bill. "
        f"Answers already bought are cached, so a re-run only pays for what is left."
    )


# --- the record cache ---------------------------------------------------------
#
# One file, keyed by content hash, holding both discharge and claim verdicts. They
# share a namespace because they share a shape: a narrow question with a yes/no
# answer, cacheable for as long as the question is unchanged.


def cache_path(project: Project) -> "Any":
    return project.state_dir / "verify" / CACHE_NAME


def load_cache(project: Project) -> dict[str, dict[str, Any]]:
    path = cache_path(project)
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def save_cache(project: Project, cache: dict[str, dict[str, Any]]) -> None:
    path = cache_path(project)
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(path, json.dumps(cache, indent=2, ensure_ascii=False, sort_keys=True) + "\n")


# --- prompts ------------------------------------------------------------------


def obligation_prompt(record: dict[str, Any]) -> str:
    """The whole question, self-contained. Deliberately carries no proof context."""
    return "\n".join(
        [
            "## The obligation",
            "",
            f"The proof of `{record['parent']}` cites `{record['child']}`.",
            f"That lemma is applied to: {record['applied_to'] or '(unstated)'}",
            "",
            f"**Needed** — hypothesis {record['hypothesis']} of `{record['child']}`:",
            "",
            f"$$ {record['needed']} $$",
            "",
            f"**Claimed source**: `{record['claimed_source']}`",
            "",
            "**What that source says**:",
            "",
            record["source_text"] or "(the source is free text, quoted above)",
        ]
    )


def claim_prompt(record: dict[str, Any]) -> str:
    """One ledger claim and its named source. No proof context, same as above."""
    return "\n".join(
        [
            "## The claim",
            "",
            f"The proof of `{record['parent']}` asserts, as claim {record['claim']}:",
            "",
            f"$$ {record['needed']} $$",
            "",
            f"**Claimed source**: `{record['claimed_source']}`",
            "",
            "**What that source says**:",
            "",
            record["source_text"] or "(the source is free text, quoted above)",
        ]
    )


def reference_prompt(record: dict[str, Any]) -> str:
    """One citation: the passage that cites, and the text cited.

    The passage matters as much as the target. Asking "does equation (3) exist" is a
    question code already answered; asking "does equation (3) give what this sentence
    draws from it" is the one that needed a reader.
    """
    return "\n".join(
        [
            "## The citation",
            "",
            f"The {record['target_section']} of `{record['parent']}` cites "
            f"`\\{record['command']}{{{record['reference']}}}`, which points into the "
            f"{record['target_section']} of `{record['target']}`.",
            "",
            "**The passage doing the citing** (the reference appears inside it):",
            "",
            record["needed"] or "(the passage is empty)",
            "",
            f"**What `{record['target']}` actually says**:",
            "",
            record["source_text"] or "(that section is empty)",
        ]
    )


def circularity_prompt(record: dict[str, Any]) -> str:
    """One upward citation, with the loop spelled out.

    The prompt has to state the graph fact, because it is the whole reason the
    question is being asked and the model cannot see the graph.
    """
    return "\n".join(
        [
            "## The citation, and why it is being questioned",
            "",
            f"`{record['parent']}` cites "
            f"`\\{record['command']}{{{record['reference']}}}`, which points into the "
            f"{record['target_section']} of `{record['target']}`.",
            "",
            f"**`{record['target']}`'s own proof cites `{record['parent']}`.** So if "
            f"`{record['parent']}` uses what `{record['target']}` asserts as a fact, "
            "each rests on the other and neither is established.",
            "",
            "**The passage doing the citing** (the reference appears inside it):",
            "",
            record["needed"] or "(the passage is empty)",
            "",
            f"**What `{record['target']}` says at that point**:",
            "",
            record["source_text"] or "(that section is empty)",
        ]
    )


def batch_prompt(records: list[dict[str, Any]], render) -> str:
    """Several records in one call.

    Batching trades reliability for cost — a model asked ten questions at once
    answers each one less carefully than a model asked one — which is why
    ``--batch`` defaults to 1 and is something the user opts into rather than
    something the system does behind their back.
    """
    parts = [
        f"You are given {len(records)} independent questions. Answer **each one on "
        "its own**, quoting its `id` back. Do not let one answer influence another; "
        "they are unrelated and are batched only to save a call.",
        "",
    ]
    for record in records:
        parts.append(f"### Question `{record['id']}`")
        parts.append("")
        parts.append(render(record))
        parts.append("")
    return "\n".join(parts)


# --- job 1 and job 2: the narrow entailment checks -----------------------------


def _check_records(
    project: Project,
    records: list[dict[str, Any]],
    *,
    registry: Registry,
    prompt_name: str,
    render,
    batch: int,
    use_cache: bool,
    schema: type[BaseModel] = ObligationVerdict,
) -> tuple[list[tuple[dict[str, Any], Any]], int, list[CallMeta]]:
    """Run one worklist through the mid-tier model. Returns verdicts and cache hits.

    The list comes from code, so nothing is skipped because a model failed to
    notice it needed checking; the cache is keyed on each record's content hash, so
    nothing is paid for twice.
    """
    if not records:
        return [], 0, []

    agent = registry.agent("obligation")
    timeout = registry.config.role("obligation").timeout
    system = context.load_prompt(prompt_name)
    cache = load_cache(project) if use_cache else {}

    out: list[tuple[dict[str, Any], Any]] = []
    calls: list[CallMeta] = []
    cached_count = 0
    pending: list[dict[str, Any]] = []

    for record in records:
        cached = cache.get(record["hash"]) if use_cache else None
        if cached is not None:
            out.append((record, schema(**cached["verdict"])))
            cached_count += 1
        else:
            pending.append(record)

    size = max(1, int(batch))
    try:
        _answer_pending(
            pending,
            out,
            calls,
            cache,
            agent=agent,
            system=system,
            render=render,
            schema=schema,
            timeout=timeout,
            size=size,
            use_cache=use_cache,
        )
    finally:
        # Whatever was answered before the exception has been paid for, and the
        # question it answers has not changed. Banking it in a `finally` is the
        # difference between a run that can be resumed and a cap that can never be
        # got past: without this, a worklist longer than the budget lost every
        # answer it had bought, so the retry re-billed from zero and died in the
        # same place, forever.
        if use_cache:
            save_cache(project, cache)
    return out, cached_count, calls


def _answer_pending(
    pending: list[dict[str, Any]],
    out: list[tuple[dict[str, Any], Any]],
    calls: list[CallMeta],
    cache: dict[str, dict[str, Any]],
    *,
    agent,
    system: str,
    render,
    schema: type[BaseModel],
    timeout: float,
    size: int,
    use_cache: bool,
) -> None:
    """The billing loop, split out so its caller can bank the cache on any exit."""
    for start in range(0, len(pending), size):
        chunk = pending[start : start + size]
        if len(chunk) == 1 or schema is not ObligationVerdict:
            # Batching is only wired for the yes/no entailment shape. A schema with
            # its own field names would need its own batch envelope, and inventing
            # one to save a call on the rarest job is a bad trade.
            answers = {}
            for record in chunk:
                verdict, meta = agent.complete(system, render(record), schema, timeout)
                calls.append(meta)
                answers[record["id"]] = verdict
        else:
            batched, meta = agent.complete(
                system, batch_prompt(chunk, render), BatchVerdict, timeout
            )
            calls.append(meta)
            answers = {
                item.id: ObligationVerdict(
                    entails=item.entails, why=item.why, confidence=item.confidence
                )
                for item in batched.verdicts
            }
        for record in chunk:
            verdict = answers.get(record["id"])
            if verdict is None:
                # A batched reply that skipped a question has not answered it, and
                # an unanswered question is not a pass. Fail it closed with a
                # reason naming the batching, so the user can see what happened.
                verdict = ObligationVerdict(
                    entails=False,
                    why="the batched reply did not answer this question; re-run with "
                    "--batch 1 to have it asked on its own",
                    confidence="low",
                )
            out.append((record, verdict))
            if use_cache:
                cache[record["hash"]] = {"id": record["id"], "verdict": verdict.model_dump()}


def verify_obligations(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyReport:
    """Job 1: every discharge in this node's ``uses`` table."""
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")

    # An ADMITTED discharge has nothing to check: the author already said it is
    # unsourced, and the sweep already carries it as visible debt.
    records = [r for r in obligations_for(node, graph) if r["kind"] != "admitted"]
    report.obligations_total = len(records)
    if not records:
        return report

    verdicts, cached, calls = _check_records(
        project,
        records,
        registry=registry,
        prompt_name="verify_obligation",
        render=obligation_prompt,
        batch=batch,
        use_cache=use_cache,
    )
    report.obligations_cached += cached
    report.obligations_checked += len(verdicts)
    report.calls.extend(calls)
    report.models.setdefault("obligation", registry.agent("obligation").model)

    for record, verdict in verdicts:
        if verdict.entails:
            report.checked.append(
                f"{record['child']}.{record['hypothesis']} from {record['claimed_source']}"
            )
        else:
            report.flags.append(
                Flag(
                    source="obligation",
                    section="proof",
                    quote=f"{record['child']} hypothesis {record['hypothesis']}: "
                    f"{record['needed']}",
                    kind="hypothesis-unsatisfied",
                    why=verdict.why,
                    raised_by=f"obligation:{report.models.get('obligation', '?')}",
                )
            )
    return report


def verify_claims(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyReport:
    """Job 2: every sourced claim in this node's ledger.

    Unsourced claims are not sent anywhere. ``LED001`` has already decided them,
    deterministically, and asking a model about a settled question would invite it
    to unsettle it.
    """
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")

    records = claim_obligations_for(node, graph)
    report.claims_total = len(records)
    if not records:
        return report

    verdicts, cached, calls = _check_records(
        project,
        records,
        registry=registry,
        prompt_name="verify_claim",
        render=claim_prompt,
        batch=batch,
        use_cache=use_cache,
    )
    report.claims_cached += cached
    report.claims_checked += len(verdicts)
    report.calls.extend(calls)
    report.models.setdefault("claim", registry.agent("obligation").model)

    for record, verdict in verdicts:
        if verdict.entails:
            report.checked.append(
                f"claim {record['claim']} from {record['claimed_source']}"
            )
        else:
            report.flags.append(
                Flag(
                    source="claim",
                    section="proof",
                    quote=f"claim {record['claim']}: {record['needed']}",
                    kind="claim-unjustified",
                    why=verdict.why,
                    raised_by=f"claim:{report.models.get('claim', '?')}",
                )
            )
    return report


def verify_references(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyReport:
    """Job 3: every cross-node citation this node's text makes.

    This job exists because of a specific failure. A target's statement said "in the
    setting of Section \\ref{sec-space}" for a section nobody had written, and four
    layers missed it: nothing examined the target when it was written, the decomposer
    propagated the phrase into every child, the verifier passed their proofs, and
    LaTeX only warned. They failed for one reason — **nobody enumerated the
    references** — which is this system's recurring lesson applied to citations.

    ``XRF001`` now answers *existence* in code. This answers the other two questions
    a compiler cannot: does the cited text say what the citing passage uses it for,
    and can it be applied here?
    """
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")

    records = xref_mod.reference_obligations_for(node, graph)
    report.references_total = len(records)
    if not records:
        return report

    # Two questions, so two worklists. A citation *down* the graph is a normal
    # citation: does the cited text support the use? A citation *up* the graph is a
    # loop candidate: is it being used as a fact at all? Asking the second one the
    # first question would get "yes, the parent asserts it" — true, and exactly the
    # wrong answer.
    upward = [r for r in records if r["relation"] == xref_mod.ANCESTOR]
    downward = [r for r in records if r["relation"] != xref_mod.ANCESTOR]

    if downward:
        verdicts, cached, calls = _check_records(
            project,
            downward,
            registry=registry,
            prompt_name="verify_reference",
            render=reference_prompt,
            batch=batch,
            use_cache=use_cache,
        )
        report.references_cached += cached
        report.references_checked += len(verdicts)
        report.calls.extend(calls)
        report.models.setdefault("reference", registry.agent("obligation").model)
        for record, verdict in verdicts:
            if verdict.entails:
                report.checked.append(
                    f"citation \\{record['command']}{{{record['reference']}}} "
                    f"-> {record['target']}"
                )
            else:
                report.flags.append(
                    Flag(
                        source="reference",
                        section=record["target_section"],
                        quote=record["needed"][:400],
                        kind="citation-misuse",
                        why=verdict.why,
                        raised_by=f"reference:{report.models.get('reference', '?')}",
                    )
                )

    if upward:
        verdicts, cached, calls = _check_records(
            project,
            upward,
            registry=registry,
            prompt_name="verify_circularity",
            render=circularity_prompt,
            batch=batch,
            use_cache=use_cache,
            schema=CircularityVerdict,
        )
        report.references_cached += cached
        report.references_checked += len(verdicts)
        report.calls.extend(calls)
        report.models.setdefault("reference", registry.agent("obligation").model)
        for record, verdict in verdicts:
            if not verdict.used_as_fact:
                report.checked.append(
                    f"citation \\{record['command']}{{{record['reference']}}} "
                    f"-> {record['target']} names it, does not assume it"
                )
            else:
                report.circular_citations += 1
                report.flags.append(
                    Flag(
                        source="reference",
                        section=record["target_section"],
                        quote=record["needed"][:400],
                        kind="circular-citation",
                        why=verdict.why,
                        context=(
                            f"`{record['target']}`'s proof rests on this node, so using "
                            f"what `{record['target']}` asserts as a fact here is a loop "
                            "with no bottom."
                        ),
                        raised_by=f"reference:{report.models.get('reference', '?')}",
                    )
                )
    return report


# --- job 4: the whole-proof pass ----------------------------------------------


def verify_proof(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    panel: tuple[str, ...] | None = None,
) -> VerifyReport:
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")
    if not node.has_proof:
        raise ops.OpError(f"{node_id} has no proof to verify")

    members = tuple(panel) if panel else tuple(registry.config.panel)
    system = context.load_prompt("verify_proof")
    user = context.join(
        context.preamble_block(project),
        context.node_block(node, heading="The claim and its proof"),
        context.children_block(graph, node)
        or "## The lemmas this proof cites\n\nNone — this is a leaf.",
        context.xref_block(graph, node),
        "The lemmas above are **assumptions**. Do not question whether they are "
        "true; each has its own node and its own verification.",
    )

    for role in members:
        report.panel.setdefault(role, verification.DID_NOT_ANSWER)
        try:
            agent = registry.agent(role)
        except Exception:
            continue
        ok, _ = agent.available()
        if not ok and not agent.replay:
            continue
        try:
            verdict, meta = agent.complete(
                system, user, ProofVerdict, registry.config.role(role).timeout
            )
        except (BudgetExceeded, ReplayMiss):
            # Running out of budget is not a verifier declining to object. It
            # must reach the caller, or a recompile would sail past its cap and
            # mark everything verified on the way.
            raise
        except AgentError:
            # One panel member failing is survivable — the other still reads the
            # proof, and the absence shows in the record as `did_not_answer`.
            # Both failing is not, and the derived status refuses it.
            continue
        report.panel_ran += 1
        report.models[role] = agent.model
        report.calls.append(meta)
        report.checked.extend(f"[{role}] {item}" for item in verdict.checked)
        report.panel[role] = (
            verification.NO_OBJECTION if not verdict.objections else verification.OBJECTION_CONFIRMED
        )
        for objection in verdict.objections:
            report.flags.append(
                Flag(
                    source=f"proof:{role}",
                    section=objection.section,
                    quote=objection.quote,
                    kind=objection.kind,
                    why=objection.why,
                    raised_by=f"{role}:{agent.model}",
                )
            )
    return report


# --- confirmation -------------------------------------------------------------


def confirm(
    project: Project,
    node_id: str,
    report: VerifyReport,
    *,
    registry: Registry | None = None,
) -> VerifyReport:
    """Re-present every objection with context; drop the ones that dissolve."""
    if not report.flags:
        return report
    registry = registry or Registry(project)
    graph, _, _ = load_graph(project)
    node = graph[node_id]
    agent = registry.agent("confirmer")
    timeout = registry.config.role("confirmer").timeout
    system = context.load_prompt("verify_confirm")
    report.models.setdefault("confirm", agent.model)

    surviving: list[Flag] = []
    for index, flag in enumerate(report.flags):
        if report.confirm_stopped:
            # The cap was reached earlier in this loop. Every remaining objection
            # stands unconfirmed, which is the same direction the AgentError branch
            # below errs in: an objection nobody could re-read is kept.
            surviving.append(_unconfirmed(flag))
            continue
        user = context.join(
            "## The objection",
            f"- Class: {flag.kind}\n- Section: {flag.section}\n"
            f"- Quoting: {flag.quote}\n- Why: {flag.why}"
            + (f"\n- Structural fact: {flag.context}" if flag.context else ""),
            "## The context it was raised against",
            context.node_block(node, heading="The claim and its proof"),
            context.children_block(graph, node),
            context.uses_block(node),
            claims_block(node),
        )
        try:
            outcome, meta = agent.complete(system, user, Confirmation, timeout)
        except BudgetExceeded as exc:
            # Confirmation is the last step, so the whole-proof passes — the two most
            # expensive calls in the run, and the only ones that are never cached —
            # have already been paid for. Letting the cap throw here discarded all of
            # it and recorded nothing, so the user paid for a verification and got an
            # error message. Instead: stop confirming, keep every remaining objection
            # unconfirmed, and record. Unconfirmed objections keep the node out of
            # `verified`, so the verdict still errs the safe way.
            report.confirm_stopped = str(exc)
            surviving.append(_unconfirmed(flag))
            continue
        except ReplayMiss:
            raise
        except AgentError:
            surviving.append(flag)  # cannot confirm; err toward keeping it
            continue
        report.calls.append(meta)
        if outcome.upheld:
            flag.why = outcome.why or flag.why
            surviving.append(flag)
        else:
            report.withdrawn.append((flag, outcome.why))

    report.flags = surviving

    # A panel objection that dissolved on confirmation is not an objection. Say so
    # in the record, or a withdrawn finding would keep the node flagged forever.
    for role in list(report.panel):
        if report.panel[role] != verification.OBJECTION_CONFIRMED:
            continue
        still = any(f.source == f"proof:{role}" for f in report.flags)
        if not still:
            report.panel[role] = verification.OBJECTION_WITHDRAWN
    return report


#: What is appended to an objection the confirmer never got to read. It lands in the
#: node file and in the rendered document, which is where objections are actually
#: read — an unconfirmed objection that looked identical to a confirmed one would be
#: a quiet downgrade in the evidence, and this system's whole job is to not do that.
UNCONFIRMED = (
    " [NOT CONFIRMED: the call cap was reached before this objection could be "
    "re-read in context, so it may be pedantry. Raise budget.max_calls_per_run or "
    "re-run — the narrow checks are cached, so a re-run is cheap.]"
)


def _unconfirmed(flag: Flag) -> Flag:
    if UNCONFIRMED not in flag.why:
        flag.why = flag.why + UNCONFIRMED
    return flag


def claims_block(node) -> str:
    """The ledger as context for the confirmation pass.

    Confirmation is the one place a whole-proof view is wanted, and an objection
    about an unstated step is often answered by a claim the extractor already found
    and sourced elsewhere in the proof.
    """
    if not node.claims:
        return ""
    lines = ["## The claim ledger for this proof", ""]
    for claim in node.claims:
        src = claim.source
        where = "UNSOURCED" if src.kind == "none" else f"{src.kind}:{src.ref}"
        lines.append(f"- {claim.id} [{where}]: {claim.text}")
    return "\n".join(lines)


# --- the whole thing ----------------------------------------------------------


def verify(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    level: str = verification.STANDARD,
    batch: int = 1,
    obligations: bool = True,
    proof: bool = True,
    record: bool = True,
) -> VerifyReport:
    """Every job the level calls for, then confirmation, then the record.

    ``obligations`` and ``proof`` narrow what runs below the level, for the CLI's
    ``--obligations-only`` and ``--proof-only``. They cannot widen it: a job the
    level does not include never runs, and the record says which ones did.
    """
    registry = registry or Registry(project)
    jobs = jobs_for(level)
    reads_proof = "whole_proof" in jobs and proof
    if record and not reads_proof:
        # A run that does not read the proof has not verified it, whatever the
        # obligations said. Refuse up front rather than writing a status nobody's
        # evidence supports.
        raise ops.OpError(
            "a verification must include the whole-proof pass. Drop --proof-only's "
            "counterpart, or pass --no-record to see obligation and claim results "
            "without writing a verdict."
        )
    report = VerifyReport(node=node_id, level=level)
    _preflight(project, node_id, registry, level=level, batch=batch)

    if "extract" in jobs and obligations:
        _refresh_ledger(project, node_id, registry=registry, report=report)

    if "obligations" in jobs and obligations:
        verify_obligations(
            project, node_id, registry=registry, report=report, batch=batch
        )
    if "references" in jobs and obligations:
        verify_references(
            project, node_id, registry=registry, report=report, batch=batch
        )
    if "claims" in jobs and obligations:
        verify_claims(project, node_id, registry=registry, report=report, batch=batch)

    if "whole_proof" in jobs and proof:
        verify_proof(project, node_id, registry=registry, report=report)

    if "audit" in jobs:
        _run_audit(project, node_id, registry=registry, report=report)

    if "confirm" in jobs:
        confirm(project, node_id, report, registry=registry)

    report.obligations_flagged = sum(1 for f in report.flags if f.source == "obligation")
    report.claims_flagged = sum(1 for f in report.flags if f.source == "claim")
    report.references_flagged = sum(1 for f in report.flags if f.source == "reference")

    from .. import checks

    graph, _, _ = load_graph(project)
    node = graph[node_id]
    report.record = verification.build(
        level=level,
        families=checks.for_node(graph, node),
        families_ran=_families_ran(report),
        ledger={
            "claims": report.ledger_claims,
            "unsourced": report.ledger_unsourced,
            "checked": report.claims_checked,
            "flagged": report.claims_flagged,
            "cached": report.claims_cached,
        }
        if report.ledger_ran
        else {},
        obligations={
            "total": report.obligations_total,
            "verified": report.obligations_checked - report.obligations_flagged,
            "flagged": report.obligations_flagged,
            "cached": report.obligations_cached,
        }
        if "obligations" in jobs and obligations
        else {},
        references={
            "total": report.references_total,
            "verified": report.references_checked - report.references_flagged,
            "flagged": report.references_flagged,
            "circular": report.circular_citations,
            "cached": report.references_cached,
        }
        if "references" in jobs and obligations
        else {},
        whole_proof=report.panel,
        statement_audit=report.statement_audit,
        models=report.models,
    )
    report.verdict = verification.implied_status(report.record)

    if reads_proof and report.panel_ran == 0:
        # Silence from every verifier is not agreement, and it is not an objection
        # either. Say what happened instead of writing a flag nobody raised.
        raise AgentError(
            f"no verifier answered for {node_id}; refusing to record a verdict. "
            "Run `bp agents` to see which backends are usable."
        )

    if record:
        ops.record_verification(
            project,
            node_id,
            report.verdict,
            [f.to_record() for f in report.flags],
            record=report.record.model_dump(),
            actor="verifier",
        )
        for flag, why in report.withdrawn:
            ops.add_note(
                project,
                node_id,
                f"Objection withdrawn on confirmation ({flag.kind}): {why}",
                actor="verifier",
            )
    return report


def _refresh_ledger(
    project: Project, node_id: str, *, registry: Registry, report: VerifyReport
) -> None:
    """Re-extract the ledger when the proof has moved, then read the audit.

    Extraction is skipped when ``claims_of`` already matches the proof on file:
    the ledger is a function of the proof text, so an unchanged proof means an
    unchanged ledger and there is nothing to buy.
    """
    from ..ledger import ledger_is_stale, summarise as ledger_summary

    graph, _, _ = load_graph(project)
    node = graph.get(node_id)
    if node is None or not node.has_proof:
        return
    if not node.claims or ledger_is_stale(node):
        try:
            result = extract_role.extract(project, node_id, registry=registry)
        except (BudgetExceeded, ReplayMiss):
            raise
        except AgentError:
            # The ledger stays as it was, and the record will say `ledger: not_run`
            # rather than reporting zero unsourced claims from an absent ledger.
            return
        report.calls.extend(result.calls)
        report.models.setdefault("extractor", registry.agent("extractor").model)
        graph, _, _ = load_graph(project)
        node = graph[node_id]

    counts = ledger_summary(node)
    report.ledger_claims = counts["claims"]
    report.ledger_unsourced = counts["unsourced"]
    report.ledger_ran = True


def _run_audit(
    project: Project, node_id: str, *, registry: Registry, report: VerifyReport
) -> None:
    """The statement audit. Its findings become a note, never a status."""
    try:
        result = audit_role.audit(project, node_id, registry=registry)
    except (BudgetExceeded, ReplayMiss):
        raise
    except (AgentError, ops.OpError):
        return
    report.calls.extend(result.calls)
    report.models.setdefault("auditor", registry.agent("auditor").model)
    report.statement_audit = result.verdict


def _families_ran(report: VerifyReport) -> list[str]:
    """Which deterministic families this run is entitled to report on.

    The ledger audit is only meaningful when a ledger exists — at ``quick`` the
    extractor never runs, so the record says ``ledger: not_run`` rather than
    ``pass``, which would be a claim about claims nobody enumerated.
    """
    families = ["integrity", "children_used", "discharge", "xref", "latex"]
    if report.ledger_ran:
        families.append("ledger")
    return families


def summarise(report: VerifyReport) -> str:
    lines = [f"{report.node}: {report.verdict} (level {report.level})"]
    if report.ledger_ran:
        lines.append(
            f"  ledger: {report.ledger_claims} claim(s), "
            f"{report.ledger_unsourced} unsourced, {report.claims_checked} checked"
        )
    if report.references_total:
        lines.append(
            f"  citations: {report.references_checked} of "
            f"{report.references_total} checked "
            f"({report.references_cached} from cache)"
            + (
                f", {report.circular_citations} CIRCULAR"
                if report.circular_citations
                else ""
            )
        )
    if report.obligations_total or report.obligations_checked:
        lines.append(
            f"  obligations: {report.obligations_checked} of "
            f"{report.obligations_total} checked "
            f"({report.obligations_cached} from cache)"
        )
    if report.panel:
        lines.append(
            "  whole proof: "
            + ", ".join(f"{k}={v}" for k, v in sorted(report.panel.items()))
        )
    if report.statement_audit != verification.NOT_RUN:
        lines.append(f"  statement audit: {report.statement_audit}")
    if report.flags:
        lines.append(f"  {len(report.flags)} objection(s) upheld:")
        for flag in report.flags:
            lines.append(f"    [{flag.kind}] {flag.why}")
            if flag.quote:
                lines.append(f"      quoting: {flag.quote[:160]}")
    if report.withdrawn:
        lines.append(f"  {len(report.withdrawn)} objection(s) withdrawn on confirmation")
    if report.verdict == "flagged":
        for reason in report.reasons:
            lines.append(f"  flagged because: {reason}")
    if not report.flags and report.checked:
        lines.append("  no objection, having checked —")
        for item in report.checked[:20]:
            lines.append(f"    - {item}")
    if report.record is not None:
        lines.append(f"  record: {verification.compact(report.record)}")
    return "\n".join(lines)


