CACHE_NAME = "obligations.json"

#: Which jobs each level runs. ``quick`` is for iterating; ``standard`` is routine
#: work; ``deep`` is what you run before trusting a subtree or writing it up.
#: Confirmation is in every level on purpose — see the module docstring.
LEVEL_JOBS: dict[str, frozenset[str]] = {
    verification.QUICK: frozenset({"whole_proof", "confirm"}),
    verification.STANDARD: frozenset(
        {"extract", "obligations", "whole_proof", "confirm"}
    ),
    verification.DEEP: frozenset(
        {"extract", "obligations", "claims", "audit", "whole_proof", "confirm"}
    ),
}

PANEL = ("verifier_a", "verifier_b")


def jobs_for(level: str) -> frozenset[str]:
    try:
        return LEVEL_JOBS[level]
    except KeyError:
        raise ops.OpError(
            f"unknown level {level!r}; the levels are "
            + ", ".join(verification.LEVELS)
        ) from None


class ObligationVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    entails: bool = Field(
        description="true only if the named source really gives the needed hypothesis "
        "for the stated object"
    )
    why: str = Field(description="one or two sentences")
    confidence: str = Field(default="medium", description="low | medium | high")


class BatchItem(ObligationVerdict):
    """One verdict inside a batched reply, tagged with the record it answers."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(description="the `id` of the record this verdict answers")


class BatchVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    verdicts: list[BatchItem] = Field(
        description="exactly one entry per record you were given, with its id"
    )


class Objection(BaseModel):
    model_config = ConfigDict(extra="forbid")

    section: str = Field(default="proof", description="statement | proof")
    quote: str = Field(description="the exact sentence or display this applies to")
    kind: str = Field(description="the class of error")
    why: str = Field(description="why it does not hold")
    confidence: str = Field(default="medium", description="low | medium | high")


class ProofVerdict(BaseModel):
    model_config = ConfigDict(extra="forbid")

    checked: list[str] = Field(
        description="what you went through, step by step. Required either way."
    )
    objections: list[Objection] = Field(default_factory=list)


class Confirmation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    upheld: bool
    why: str = Field(description="one sentence: the flaw, or what resolved it")


@dataclass
class Flag:
    """An objection that survived confirmation."""

    source: str
    section: str
    quote: str
    kind: str
    why: str
    raised_by: str

    def to_record(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "section": self.section,
            "quote": self.quote,
            "why": self.why,
            "raised_by": self.raised_by,
        }


@dataclass
class VerifyReport:
    node: str
    level: str = verification.STANDARD
    obligations_total: int = 0
    obligations_checked: int = 0
    obligations_cached: int = 0
    obligations_flagged: int = 0
    claims_total: int = 0
    claims_checked: int = 0
    claims_cached: int = 0
    claims_flagged: int = 0
    ledger_claims: int = 0
    ledger_unsourced: int = 0
    ledger_ran: bool = False
    #: How many panel members actually answered. Zero means nothing verified this
    #: proof, which must never be recorded as ``verified``.
    panel_ran: int = 0
    panel: dict[str, str] = field(default_factory=dict)
    statement_audit: str = verification.NOT_RUN
    models: dict[str, str] = field(default_factory=dict)
    flags: list[Flag] = field(default_factory=list)
    withdrawn: list[tuple[Flag, str]] = field(default_factory=list)
    checked: list[str] = field(default_factory=list)
    calls: list[CallMeta] = field(default_factory=list)
    record: Any = None
    verdict: str = "verified"

    @property
    def reasons(self) -> list[str]:
        return verification.reasons(self.record) if self.record is not None else []


# --- the record cache ---------------------------------------------------------
#
# One file, keyed by content hash, holding both discharge and claim verdicts. They
# share a namespace because they share a shape: a narrow question with a yes/no
# answer, cacheable for as long as the question is unchanged.


def cache_path(project: Project) -> "Any":
    return project.state_dir / "verify" / CACHE_NAME


def load_cache(project: Project) -> dict[str, dict[str, Any]]:
    path = cache_path(project)
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def save_cache(project: Project, cache: dict[str, dict[str, Any]]) -> None:
    path = cache_path(project)
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(path, json.dumps(cache, indent=2, ensure_ascii=False, sort_keys=True) + "\n")


# --- prompts ------------------------------------------------------------------


def obligation_prompt(record: dict[str, Any]) -> str:
    """The whole question, self-contained. Deliberately carries no proof context."""
    return "\n".join(
        [
            "## The obligation",
            "",
            f"The proof of `{record['parent']}` cites `{record['child']}`.",
            f"That lemma is applied to: {record['applied_to'] or '(unstated)'}",
            "",
            f"**Needed** — hypothesis {record['hypothesis']} of `{record['child']}`:",
            "",
            f"$$ {record['needed']} $$",
            "",
            f"**Claimed source**: `{record['claimed_source']}`",
            "",
            "**What that source says**:",
            "",
            record["source_text"] or "(the source is free text, quoted above)",
        ]
    )


def claim_prompt(record: dict[str, Any]) -> str:
    """One ledger claim and its named source. No proof context, same as above."""
    return "\n".join(
        [
            "## The claim",
            "",
            f"The proof of `{record['parent']}` asserts, as claim {record['claim']}:",
            "",
            f"$$ {record['needed']} $$",
            "",
            f"**Claimed source**: `{record['claimed_source']}`",
            "",
            "**What that source says**:",
            "",
            record["source_text"] or "(the source is free text, quoted above)",
        ]
    )


def batch_prompt(records: list[dict[str, Any]], render) -> str:
    """Several records in one call.

    Batching trades reliability for cost — a model asked ten questions at once
    answers each one less carefully than a model asked one — which is why
    ``--batch`` defaults to 1 and is something the user opts into rather than
    something the system does behind their back.
    """
    parts = [
        f"You are given {len(records)} independent questions. Answer **each one on "
        "its own**, quoting its `id` back. Do not let one answer influence another; "
        "they are unrelated and are batched only to save a call.",
        "",
    ]
    for record in records:
        parts.append(f"### Question `{record['id']}`")
        parts.append("")
        parts.append(render(record))
        parts.append("")
    return "\n".join(parts)


# --- job 1 and job 2: the narrow entailment checks -----------------------------


def _check_records(
    project: Project,
    records: list[dict[str, Any]],
    *,
    registry: Registry,
    prompt_name: str,
    render,
    batch: int,
    use_cache: bool,
) -> tuple[list[tuple[dict[str, Any], ObligationVerdict]], int, list[CallMeta]]:
    """Run one worklist through the mid-tier model. Returns verdicts and cache hits.

    The list comes from code, so nothing is skipped because a model failed to
    notice it needed checking; the cache is keyed on each record's content hash, so
    nothing is paid for twice.
    """
    if not records:
        return [], 0, []

    agent = registry.agent("obligation")
    timeout = registry.config.role("obligation").timeout
    system = context.load_prompt(prompt_name)
    cache = load_cache(project) if use_cache else {}

    out: list[tuple[dict[str, Any], ObligationVerdict]] = []
    calls: list[CallMeta] = []
    cached_count = 0
    pending: list[dict[str, Any]] = []

    for record in records:
        cached = cache.get(record["hash"]) if use_cache else None
        if cached is not None:
            out.append((record, ObligationVerdict(**cached["verdict"])))
            cached_count += 1
        else:
            pending.append(record)

    size = max(1, int(batch))
    for start in range(0, len(pending), size):
        chunk = pending[start : start + size]
        if len(chunk) == 1:
            verdict, meta = agent.complete(system, render(chunk[0]), ObligationVerdict, timeout)
            calls.append(meta)
            answers = {chunk[0]["id"]: verdict}
        else:
            batched, meta = agent.complete(
                system, batch_prompt(chunk, render), BatchVerdict, timeout
            )
            calls.append(meta)
            answers = {
                item.id: ObligationVerdict(
                    entails=item.entails, why=item.why, confidence=item.confidence
                )
                for item in batched.verdicts
            }
        for record in chunk:
            verdict = answers.get(record["id"])
            if verdict is None:
                # A batched reply that skipped a question has not answered it, and
                # an unanswered question is not a pass. Fail it closed with a
                # reason naming the batching, so the user can see what happened.
                verdict = ObligationVerdict(
                    entails=False,
                    why="the batched reply did not answer this question; re-run with "
                    "--batch 1 to have it asked on its own",
                    confidence="low",
                )
            out.append((record, verdict))
            if use_cache:
                cache[record["hash"]] = {"id": record["id"], "verdict": verdict.model_dump()}

    if use_cache:
        save_cache(project, cache)
    return out, cached_count, calls


def verify_obligations(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyReport:
    """Job 1: every discharge in this node's ``uses`` table."""
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")

    # An ADMITTED discharge has nothing to check: the author already said it is
    # unsourced, and the sweep already carries it as visible debt.
    records = [r for r in obligations_for(node, graph) if r["kind"] != "admitted"]
    report.obligations_total = len(records)
    if not records:
        return report

    verdicts, cached, calls = _check_records(
        project,
        records,
        registry=registry,
        prompt_name="verify_obligation",
        render=obligation_prompt,
        batch=batch,
        use_cache=use_cache,
    )
    report.obligations_cached += cached
    report.obligations_checked += len(verdicts)
    report.calls.extend(calls)
    report.models.setdefault("obligation", registry.agent("obligation").model)

    for record, verdict in verdicts:
        if verdict.entails:
            report.checked.append(
                f"{record['child']}.{record['hypothesis']} from {record['claimed_source']}"
            )
        else:
            report.flags.append(
                Flag(
                    source="obligation",
                    section="proof",
                    quote=f"{record['child']} hypothesis {record['hypothesis']}: "
                    f"{record['needed']}",
                    kind="hypothesis-unsatisfied",
                    why=verdict.why,
                    raised_by=f"obligation:{report.models.get('obligation', '?')}",
                )
            )
    return report


def verify_claims(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    use_cache: bool = True,
    batch: int = 1,
) -> VerifyReport:
    """Job 2: every sourced claim in this node's ledger.

    Unsourced claims are not sent anywhere. ``LED001`` has already decided them,
    deterministically, and asking a model about a settled question would invite it
    to unsettle it.
    """
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")

    records = claim_obligations_for(node, graph)
    report.claims_total = len(records)
    if not records:
        return report

    verdicts, cached, calls = _check_records(
        project,
        records,
        registry=registry,
        prompt_name="verify_claim",
        render=claim_prompt,
        batch=batch,
        use_cache=use_cache,
    )
    report.claims_cached += cached
    report.claims_checked += len(verdicts)
    report.calls.extend(calls)
    report.models.setdefault("claim", registry.agent("obligation").model)

    for record, verdict in verdicts:
        if verdict.entails:
            report.checked.append(
                f"claim {record['claim']} from {record['claimed_source']}"
            )
        else:
            report.flags.append(
                Flag(
                    source="claim",
                    section="proof",
                    quote=f"claim {record['claim']}: {record['needed']}",
                    kind="claim-unjustified",
                    why=verdict.why,
                    raised_by=f"claim:{report.models.get('claim', '?')}",
                )
            )
    return report


# --- job 3: the whole-proof pass ----------------------------------------------


def verify_proof(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    report: VerifyReport | None = None,
    panel: tuple[str, ...] = PANEL,
) -> VerifyReport:
    registry = registry or Registry(project)
    report = report or VerifyReport(node=node_id)
    graph, _, swept = load_graph(project)
    if not swept:
        raise ops.OpError("the graph has a cycle; run `bp check` first")
    node = graph.get(node_id)
    if node is None:
        raise ops.OpError(f"no node {node_id!r}")
    if not node.has_proof:
        raise ops.OpError(f"{node_id} has no proof to verify")

    system = context.load_prompt("verify_proof")
    user = context.join(
        context.preamble_block(project),
        context.node_block(node, heading="The claim and its proof"),
        context.children_block(graph, node)
        or "## The lemmas this proof cites\n\nNone — this is a leaf.",
        context.xref_block(graph, node),
        "The lemmas above are **assumptions**. Do not question whether they are "
        "true; each has its own node and its own verification.",
    )

    for role in panel:
        report.panel.setdefault(role, verification.DID_NOT_ANSWER)
        try:
            agent = registry.agent(role)
        except Exception:
            continue
        ok, _ = agent.available()
        if not ok and not agent.replay:
            continue
        try:
            verdict, meta = agent.complete(
                system, user, ProofVerdict, registry.config.role(role).timeout
            )
        except (BudgetExceeded, ReplayMiss):
            # Running out of budget is not a verifier declining to object. It
            # must reach the caller, or a recompile would sail past its cap and
            # mark everything verified on the way.
            raise
        except AgentError:
            # One panel member failing is survivable — the other still reads the
            # proof, and the absence shows in the record as `did_not_answer`.
            # Both failing is not, and the derived status refuses it.
            continue
        report.panel_ran += 1
        report.models[role] = agent.model
        report.calls.append(meta)
        report.checked.extend(f"[{role}] {item}" for item in verdict.checked)
        report.panel[role] = (
            verification.NO_OBJECTION if not verdict.objections else verification.OBJECTION_CONFIRMED
        )
        for objection in verdict.objections:
            report.flags.append(
                Flag(
                    source=f"proof:{role}",
                    section=objection.section,
                    quote=objection.quote,
                    kind=objection.kind,
                    why=objection.why,
                    raised_by=f"{role}:{agent.model}",
                )
            )
    return report


# --- confirmation -------------------------------------------------------------


def confirm(
    project: Project,
    node_id: str,
    report: VerifyReport,
    *,
    registry: Registry | None = None,
) -> VerifyReport:
    """Re-present every objection with context; drop the ones that dissolve."""
    if not report.flags:
        return report
    registry = registry or Registry(project)
    graph, _, _ = load_graph(project)
    node = graph[node_id]
    agent = registry.agent("confirmer")
    timeout = registry.config.role("confirmer").timeout
    system = context.load_prompt("verify_confirm")
    report.models.setdefault("confirm", agent.model)

    surviving: list[Flag] = []
    for flag in report.flags:
        user = context.join(
            "## The objection",
            f"- Class: {flag.kind}\n- Section: {flag.section}\n"
            f"- Quoting: {flag.quote}\n- Why: {flag.why}",
            "## The context it was raised against",
            context.node_block(node, heading="The claim and its proof"),
            context.children_block(graph, node),
            context.uses_block(node),
            claims_block(node),
        )
        try:
            outcome, meta = agent.complete(system, user, Confirmation, timeout)
        except (BudgetExceeded, ReplayMiss):
            raise
        except AgentError:
            surviving.append(flag)  # cannot confirm; err toward keeping it
            continue
        report.calls.append(meta)
        if outcome.upheld:
            flag.why = outcome.why or flag.why
            surviving.append(flag)
        else:
            report.withdrawn.append((flag, outcome.why))

    report.flags = surviving

    # A panel objection that dissolved on confirmation is not an objection. Say so
    # in the record, or a withdrawn finding would keep the node flagged forever.
    for role in list(report.panel):
        if report.panel[role] != verification.OBJECTION_CONFIRMED:
            continue
        still = any(f.source == f"proof:{role}" for f in report.flags)
        if not still:
            report.panel[role] = verification.OBJECTION_WITHDRAWN
    return report


def claims_block(node) -> str:
    """The ledger as context for the confirmation pass.

    Confirmation is the one place a whole-proof view is wanted, and an objection
    about an unstated step is often answered by a claim the extractor already found
    and sourced elsewhere in the proof.
    """
    if not node.claims:
        return ""
    lines = ["## The claim ledger for this proof", ""]
    for claim in node.claims:
        src = claim.source
        where = "UNSOURCED" if src.kind == "none" else f"{src.kind}:{src.ref}"
        lines.append(f"- {claim.id} [{where}]: {claim.text}")
    return "\n".join(lines)


# --- the whole thing ----------------------------------------------------------


def verify(
    project: Project,
    node_id: str,
    *,
    registry: Registry | None = None,
    level: str = verification.STANDARD,
    batch: int = 1,
    obligations: bool = True,
    proof: bool = True,
    record: bool = True,
) -> VerifyReport:
    """Every job the level calls for, then confirmation, then the record.

    ``obligations`` and ``proof`` narrow what runs below the level, for the CLI's
    ``--obligations-only`` and ``--proof-only``. They cannot widen it: a job the
    level does not include never runs, and the record says which ones did.
    """
    registry = registry or Registry(project)
    jobs = jobs_for(level)
    reads_proof = "whole_proof" in jobs and proof
    if record and not reads_proof:
        # A run that does not read the proof has not verified it, whatever the
        # obligations said. Refuse up front rather than writing a status nobody's
        # evidence supports.
        raise ops.OpError(
            "a verification must include the whole-proof pass. Drop --proof-only's "
            "counterpart, or pass --no-record to see obligation and claim results "
            "without writing a verdict."
        )
    report = VerifyReport(node=node_id, level=level)

    if "extract" in jobs and obligations:
        _refresh_ledger(project, node_id, registry=registry, report=report)

    if "obligations" in jobs and obligations:
        verify_obligations(
            project, node_id, registry=registry, report=report, batch=batch
        )
    if "claims" in jobs and obligations:
        verify_claims(project, node_id, registry=registry, report=report, batch=batch)

    if "whole_proof" in jobs and proof:
        verify_proof(project, node_id, registry=registry, report=report)

    if "audit" in jobs:
        _run_audit(project, node_id, registry=registry, report=report)

    if "confirm" in jobs:
        confirm(project, node_id, report, registry=registry)

    report.obligations_flagged = sum(1 for f in report.flags if f.source == "obligation")
    report.claims_flagged = sum(1 for f in report.flags if f.source == "claim")

    from .. import checks

    graph, _, _ = load_graph(project)
    node = graph[node_id]
    report.record = verification.build(
        level=level,
        families=checks.for_node(graph, node),
        families_ran=_families_ran(report),
        ledger={
            "claims": report.ledger_claims,
            "unsourced": report.ledger_unsourced,
            "checked": report.claims_checked,
            "flagged": report.claims_flagged,
            "cached": report.claims_cached,
        }
        if report.ledger_ran
        else {},
        obligations={
            "total": report.obligations_total,
            "verified": report.obligations_checked - report.obligations_flagged,
            "flagged": report.obligations_flagged,
            "cached": report.obligations_cached,
        }
        if "obligations" in jobs and obligations
        else {},
        whole_proof=report.panel,
        statement_audit=report.statement_audit,
        models=report.models,
    )
    report.verdict = verification.implied_status(report.record)

    if reads_proof and report.panel_ran == 0:
        # Silence from every verifier is not agreement, and it is not an objection
        # either. Say what happened instead of writing a flag nobody raised.
        raise AgentError(
            f"no verifier answered for {node_id}; refusing to record a verdict. "
            "Run `bp agents` to see which backends are usable."
        )

    if record:
        ops.record_verification(
            project,
            node_id,
            report.verdict,
            [f.to_record() for f in report.flags],
            record=report.record.model_dump(),
            actor="verifier",
        )
        for flag, why in report.withdrawn:
            ops.add_note(
                project,
                node_id,
                f"Objection withdrawn on confirmation ({flag.kind}): {why}",
                actor="verifier",
            )
    return report


def _refresh_ledger(
    project: Project, node_id: str, *, registry: Registry, report: VerifyReport
) -> None:
    """Re-extract the ledger when the proof has moved, then read the audit.

    Extraction is skipped when ``claims_of`` already matches the proof on file:
    the ledger is a function of the proof text, so an unchanged proof means an
    unchanged ledger and there is nothing to buy.
    """
    from ..ledger import ledger_is_stale, summarise as ledger_summary

    graph, _, _ = load_graph(project)
    node = graph.get(node_id)
    if node is None or not node.has_proof:
        return
    if not node.claims or ledger_is_stale(node):
        try:
            result = extract_role.extract(project, node_id, registry=registry)
        except (BudgetExceeded, ReplayMiss):
            raise
        except AgentError:
            # The ledger stays as it was, and the record will say `ledger: not_run`
            # rather than reporting zero unsourced claims from an absent ledger.
            return
        report.calls.extend(result.calls)
        report.models.setdefault("extractor", registry.agent("extractor").model)
        graph, _, _ = load_graph(project)
        node = graph[node_id]

    counts = ledger_summary(node)
    report.ledger_claims = counts["claims"]
    report.ledger_unsourced = counts["unsourced"]
    report.ledger_ran = True


def _run_audit(
    project: Project, node_id: str, *, registry: Registry, report: VerifyReport
) -> None:
    """The statement audit. Its findings become a note, never a status."""
    try:
        result = audit_role.audit(project, node_id, registry=registry)
    except (BudgetExceeded, ReplayMiss):
        raise
    except (AgentError, ops.OpError):
        return
    report.calls.extend(result.calls)
    report.models.setdefault("auditor", registry.agent("auditor").model)
    report.statement_audit = result.verdict


def _families_ran(report: VerifyReport) -> list[str]:
    """Which deterministic families this run is entitled to report on.

    The ledger audit is only meaningful when a ledger exists — at ``quick`` the
    extractor never runs, so the record says ``ledger: not_run`` rather than
    ``pass``, which would be a claim about claims nobody enumerated.
    """
    families = ["integrity", "children_used", "discharge", "xref"]
    if report.ledger_ran:
        families.append("ledger")
    return families


def summarise(report: VerifyReport) -> str:
    lines = [f"{report.node}: {report.verdict} (level {report.level})"]
    if report.ledger_ran:
        lines.append(
            f"  ledger: {report.ledger_claims} claim(s), "
            f"{report.ledger_unsourced} unsourced, {report.claims_checked} checked"
        )
    if report.obligations_total or report.obligations_checked:
        lines.append(
            f"  obligations: {report.obligations_checked} of "
            f"{report.obligations_total} checked "
            f"({report.obligations_cached} from cache)"
        )
    if report.panel:
        lines.append(
            "  whole proof: "
            + ", ".join(f"{k}={v}" for k, v in sorted(report.panel.items()))
        )
    if report.statement_audit != verification.NOT_RUN:
        lines.append(f"  statement audit: {report.statement_audit}")
    if report.flags:
        lines.append(f"  {len(report.flags)} objection(s) upheld:")
        for flag in report.flags:
            lines.append(f"    [{flag.kind}] {flag.why}")
            if flag.quote:
                lines.append(f"      quoting: {flag.quote[:160]}")
    if report.withdrawn:
        lines.append(f"  {len(report.withdrawn)} objection(s) withdrawn on confirmation")
    if report.verdict == "flagged":
        for reason in report.reasons:
            lines.append(f"  flagged because: {reason}")
    if not report.flags and report.checked:
        lines.append("  no objection, having checked —")
        for item in report.checked[:20]:
            lines.append(f"    - {item}")
    if report.record is not None:
        lines.append(f"  record: {verification.compact(report.record)}")
    return "\n".join(lines)


